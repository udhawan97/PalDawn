import assert from 'node:assert/strict'
import { existsSync, readFileSync } from 'node:fs'

const ROOT = new URL('..', import.meta.url)
const read = (path) => readFileSync(new URL(path, ROOT), 'utf8')

const app = read('src/App.tsx')
const deck = read('src/ui/FlightDeck.tsx')
const settings = read('src/state/settings.ts')
const experience = read('src/state/experience.ts')
const journey = read('src/journey/journey.ts')
const localData = read('src/platform/localData.ts')
const pwa = read('src/platform/pwa.ts')
const serviceWorker = read('public/sw.js')
const builtServiceWorker = read('dist/sw.js')
const manifest = JSON.parse(read('public/site.webmanifest'))
const icon = read('public/icon.svg')
const staticIcon = read('public/icon-static.svg')
const indexHtml = read('index.html')

assert.match(settings, /persist<SettingsState/)
assert.match(settings, /partialize:/)
assert.match(localData, /paldawn:settings:v1/)
assert.match(localData, /paldawn:journey:v1/)
assert.match(localData, /paldawn:reset:v1/)
assert.match(localData, /readString\(PALDAWN_RESET_KEY\) !== resetTokenAtLoad/, 'stale tabs must not rewrite reset data')
assert.match(localData, /candidate\.resetToken !== currentResetToken/, 'stale reset generations must not restore')
assert.match(deck, /Resume at/)
assert.match(experience, /loadJourneySession/)
assert.match(journey, /stageIdFromHash/)
assert.match(journey, /stage\/\$\{encodeURIComponent\(id\)\}/)
assert.match(deck, /Copy this stage link/)
assert.match(deck, /Copy transcript/)
assert.match(deck, /Download text/)
assert.match(deck, /window\.print\(\)/)
assert.match(pwa, /serviceWorker\.register/)
assert.match(pwa, /update-ready/)
assert.match(pwa, /updateActivationRequested/)
assert.equal(manifest.display, 'standalone')
assert.equal(manifest.name, 'PalDawn — Systems Atlas')
assert.ok(manifest.icons.some(({ src, sizes, purpose }) => src === 'icon-512.png' && sizes === '512x512' && purpose === 'any'))
assert.ok(manifest.icons.some(({ src, purpose }) => src === 'icon-maskable-512.png' && purpose === 'maskable'))
assert.match(icon, /prefers-reduced-motion:\s*reduce/)
assert.match(icon, /class="traveler"/)
assert.doesNotMatch(staticIcon, /@keyframes|class="traveler"/)
assert.match(deck, /className="brand-icon"/)
assert.match(deck, /reducedMotion \? 'icon-static\.svg' : 'icon\.svg'/)
assert.match(read('src/App.tsx'), /reducedMotion \? 'icon-static\.svg' : 'icon\.svg'/)
assert.match(indexHtml, /paldawn-social\.png/)
assert.match(indexHtml, /rel="apple-touch-icon"/)
assert.ok(existsSync(new URL('dist/sw.js', ROOT)), 'service worker must be copied to dist')
assert.match(deck, /function HelpPanel/)
assert.match(deck, /event\.key === '\?'/)
assert.match(deck, /Copy diagnostics/)
assert.match(app, /Retry the scene/)
assert.match(app, /Continue without 3D/)
assert.match(deck, /TEXT VOYAGE/)
assert.match(settings, /captionScale/)
assert.match(deck, /visibilitychange/)
assert.match(deck, /Download local data/)
assert.match(deck, /Confirm reset/)
assert.match(deck, /requestFullscreen/)
assert.match(deck, /function CompletionSummary/)
assert.match(deck, /id="completion-summary"/)
assert.match(deck, /id="flight-controls"[^>]+tabIndex=\{-1\}/)
assert.match(deck, /event\.key !== PALDAWN_RESET_KEY/)
assert.match(deck, /entered && !textVoyage/, 'resume position overlays must stay off the intro')
assert.match(deck, /stageIdFromHash\(window\.location\.hash\) === currentStageId/)
assert.match(experience, /direction === 1 && current === JOURNEY\.stages\.length - 1/)

assert.doesNotMatch(serviceWorker, /https?:\/\//i, 'offline shell must not fetch third-party origins')
assert.match(serviceWorker, /request\.mode === 'navigate'/)
assert.match(serviceWorker, /SKIP_WAITING/)
assert.match(serviceWorker, /name\.startsWith\(CACHE_PREFIX\)/, 'cache cleanup must remain PalDawn-scoped')
assert.match(serviceWorker, /__PALDAWN_BUILD_ID__/)
assert.doesNotMatch(builtServiceWorker, /__PALDAWN_BUILD_ID__/, 'built worker must be fingerprinted')
assert.match(builtServiceWorker, /const BUILD_ID = '[a-f0-9]{12}'/)

console.log('foundation+ checks: 14 features · versioned local-only storage · offline shell intact')
